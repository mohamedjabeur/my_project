#!/usr/bin/env python3
"""Generate a Shell Eco-marathon style closed circuit (~1 km) for Gazebo.

Outputs (in the output directory, default ./track):
  road.obj, edge_lines.obj, start_line.obj, pit_lane.obj
  shell_eco_track.sdf   (world: grass + the meshes above)

Run:  python3 generate_track.py [outdir]
Then: ign gazebo -r track/shell_eco_track.sdf
"""
import math
import os
import sys

TARGET_LAP = 1000.0   # lap length (m)
ROAD_W = 7.0          # road width (m)
LINE_W = 0.15         # white line width (m)
STEP = 1.0            # centreline sampling (m)
PIT_W = 4.0           # pit lane width (m)
PIT_OFFSET = 4.5      # pit lane inner edge distance from centreline (m)
PIT_S0, PIT_S1 = 30.0, 140.0   # pit lane extent along the first straight (m)
Z_ROAD, Z_LINE = 0.02, 0.03
STOP_EVERY = 150.0    # one stop sign (+ stop line) every 150 m
PIT_S1_OVERRIDE = None

# rough layout (m): two straights, a hairpin and a sweeping bend
CTRL = [(0, 0), (120, -10), (220, 10), (265, 70), (235, 130), (150, 150),
        (100, 110), (60, 150), (-10, 160), (-70, 120), (-60, 50)]


def catmull_rom_closed(pts, step):
    n = len(pts)
    out = []
    for i in range(n):
        p0, p1, p2, p3 = (pts[(i + k - 1) % n] for k in range(4))
        for j in range(40):
            t = j / 40
            out.append(tuple(
                0.5 * ((2 * p1[c]) + (-p0[c] + p2[c]) * t
                       + (2 * p0[c] - 5 * p1[c] + 4 * p2[c] - p3[c]) * t * t
                       + (-p0[c] + 3 * p1[c] - 3 * p2[c] + p3[c]) * t ** 3)
                for c in range(2)))
    # resample at constant arc length
    cum = [0.0]
    for i in range(len(out)):
        a, b = out[i], out[(i + 1) % len(out)]
        cum.append(cum[-1] + math.dist(a, b))
    total = cum[-1]
    count = max(int(total // step), 8)
    res, k = [], 0
    for m in range(count):
        s = m * total / count
        while cum[k + 1] < s:
            k += 1
        a, b = out[k], out[(k + 1) % len(out)]
        f = (s - cum[k]) / (cum[k + 1] - cum[k])
        res.append((a[0] + f * (b[0] - a[0]), a[1] + f * (b[1] - a[1])))
    return res, total


# --- centreline, scaled so the lap is TARGET_LAP long
_, raw_len = catmull_rom_closed(CTRL, 1.0)
k = TARGET_LAP / raw_len
CL, LAP = catmull_rom_closed([(x * k, y * k) for x, y in CTRL], STEP)
N = len(CL)
DS = LAP / N

# unit tangent and left normal at each sample
NORM = []
for i in range(N):
    a, b = CL[i - 1], CL[(i + 1) % N]
    d = math.hypot(b[0] - a[0], b[1] - a[1])
    tx, ty = (b[0] - a[0]) / d, (b[1] - a[1]) / d
    NORM.append((-ty, tx))


def off(i, d):
    """Point at lateral offset d (left positive) from centreline sample i."""
    return (CL[i % N][0] + NORM[i % N][0] * d, CL[i % N][1] + NORM[i % N][1] * d)


class Mesh:
    def __init__(self):
        self.v, self.f = [], []

    def quad(self, p00, p01, p11, p10, z):
        """Quad given counter-clockwise seen from above."""
        base = len(self.v)
        self.v += [(p[0], p[1], z) for p in (p00, p01, p11, p10)]
        self.f += [(base, base + 1, base + 2), (base, base + 2, base + 3)]

    def ribbon(self, i0, i1, d0, d1, z):
        """Strip between lateral offsets d0<d1 over samples i0..i1."""
        for i in range(i0, i1):
            self.quad(off(i, d0), off(i + 1, d0), off(i + 1, d1), off(i, d1), z)

    def save(self, path):
        with open(path, "w") as fh:
            fh.write("# generated by generate_track.py\n")
            for x, y, z in self.v:
                fh.write(f"v {x:.4f} {y:.4f} {z:.4f}\n")
            fh.write("vn 0 0 1\n")
            for a, b, c in self.f:
                fh.write(f"f {a+1}//1 {b+1}//1 {c+1}//1\n")


half = ROAD_W / 2
road, edges, start, pit = Mesh(), Mesh(), Mesh(), Mesh()

# road: oriented so that left offset is +d (CCW triangles seen from above)
road.ribbon(0, N, -half, half, Z_ROAD)

# white edge lines (inside the road edge)
for d0, d1 in ((half - LINE_W - 0.05, half - 0.05), (-half + 0.05, -half + LINE_W + 0.05)):
    edges.ribbon(0, N, d0, d1, Z_LINE)


# chequered start/finish line (8 cols x 2 rows) across the road at sample 20
SL = 20
cols = 14
cw = ROAD_W / cols
rows = 2
check_white = Mesh()
for c in range(cols):
    for r in range(rows):
        if (c + r) % 2 == 0:
            d0 = -half + c * cw
            i0 = SL + r
            (check_white if True else start).quad(
                off(i0, d0), off(i0 + 1, d0), off(i0 + 1, d0 + cw), off(i0, d0 + cw), Z_LINE)
start = check_white

# pit lane on the right (outside of the loop) of the first straight
i0, i1 = int(PIT_S0 / DS), int(PIT_S1 / DS)
pit.ribbon(i0, i1, -(PIT_OFFSET + PIT_W), -PIT_OFFSET, Z_ROAD)

# --- sanity check: non-adjacent parts of the track must not overlap
min_gap = min(math.dist(CL[a], CL[b])
              for a in range(N) for b in range(a + 1, N, 3)
              if min(b - a, N - (b - a)) > 40)
if min_gap < ROAD_W + 2:
    sys.exit(f"track self-overlaps (closest approach {min_gap:.1f} m); adjust CTRL")

out = sys.argv[1] if len(sys.argv) > 1 else "track"
os.makedirs(out, exist_ok=True)
absout = os.path.abspath(out)
for name, m in (("road", road), ("edge_lines", edges),
                ("start_line", start), ("pit_lane", pit)):
    m.save(os.path.join(out, name + ".obj"))


def label_plugin(n):
    """Semantic label read by a segmentation_camera (dataset generation)."""
    return (f'<plugin filename="ignition-gazebo-label-system" '
            f'name="ignition::gazebo::systems::Label"><label>{n}</label></plugin>') if n else ""


def model(name, mesh, rgb, collision, label=0):
    col = f"""
      <collision name="c"><geometry><mesh><uri>file://{absout}/{mesh}.obj</uri></mesh></geometry></collision>""" if collision else ""
    return f"""
    <model name="{name}"><static>true</static><link name="l">
      <visual name="v"><geometry><mesh><uri>file://{absout}/{mesh}.obj</uri></mesh></geometry>
        <material><ambient>{rgb}</ambient><diffuse>{rgb}</diffuse><specular>0 0 0 1</specular></material>{label_plugin(label)}</visual>{col}
    </link></model>"""


# --- obstacles for lidar / camera testing -----------------------------------
# (arc length s in m, lateral offset d in m (left +), kind).  Each obstacle only
# covers part of the road; at most one per cross-section, so a clear lane of
# whole other lane remains free: the car changes lane, never leaves the circuit.
MIN_CLEAR = 4.0
COLORS = {"red": "0.85 0.1 0.1 1", "blue": "0.1 0.2 0.85 1", "green": "0.1 0.7 0.2 1",
          "yellow": "0.95 0.8 0.1 1", "orange": "1 0.45 0.05 1", "white": "0.9 0.9 0.9 1"}
LANE_C = ROAD_W / 4     # centre of each of the 2 lanes (+ = left lane, - = right lane)
L_, R_ = LANE_C, -LANE_C
import random
_rng = random.Random(42)                # fixed seed: same track every run
_KINDS = ["cone", "cone", "cone", "box:red", "box:blue", "box:green", "box:yellow",
          "barrel:blue", "barrel:red", "barrel:orange", "person:yellow", "person:green",
          "person:red", "bigbox:green", "bigbox:yellow", "bigbox:blue", "wall:white", "wall:orange"]
OBST = []
_s, _lane = 50.0, R_
while _s < LAP - 60:                    # keep the start line area clear
    if _rng.random() < 0.7:             # usually switch lane, sometimes stay in the same one
        _lane = -_lane
    OBST.append((round(_s), _lane, _rng.choice(_KINDS)))
    _s += _rng.uniform(9, 14)
STOPS = [STOP_EVERY * k for k in range(1, int(LAP // STOP_EVERY) + 1)]
OBST = [o for o in OBST if all(abs(o[0] - t) > 8 for t in STOPS)]
# kind -> (size along, size lateral, height, shape, colour)
SPEC = {"cone": (0.3, 0.3, 0.7, "cone", "orange"),
        "box": (1.0, 1.0, 1.0, "box", None), "bigbox": (2.0, 1.0, 1.2, "box", None),
        "barrel": (0.6, 0.6, 0.9, "cyl", None), "person": (0.4, 0.4, 1.7, "cyl", None),
        "wall": (4.0, 0.4, 0.8, "box", None)}

obst_models = []
for idx, (s, d, kind) in enumerate(OBST):
    base, _, col = kind.partition(":")
    sa, sl, h, shape, defcol = SPEC[base]
    rgb = COLORS[col or defcol]
    # must sit inside one lane and leave the other lane free
    if abs(d) != LANE_C or sl > LANE_C or (idx and s - OBST[idx - 1][0] < 8):
        sys.exit(f"obstacle {idx} ({kind}) is not cleanly inside one lane / too close to previous")
    i = int(s / DS) % N
    px, py = off(i, d)
    yaw = math.atan2(-NORM[i][0], NORM[i][1])      # heading of the track
    if shape == "box":
        geom = f"<box><size>{sa} {sl} {h}</size></box>"
        vis = f"""<visual name="v"><pose>0 0 {h/2} 0 0 0</pose><geometry>{geom}</geometry>
        <material><ambient>{rgb}</ambient><diffuse>{rgb}</diffuse></material></visual>"""
        cgeom = geom
    elif shape == "cyl":
        geom = f"<cylinder><radius>{sa/2}</radius><length>{h}</length></cylinder>"
        vis = f"""<visual name="v"><pose>0 0 {h/2} 0 0 0</pose><geometry>{geom}</geometry>
        <material><ambient>{rgb}</ambient><diffuse>{rgb}</diffuse></material></visual>"""
        cgeom = geom
    else:  # cone: stacked cylinders on a square base
        parts = [f"""<visual name="b"><pose>0 0 0.015 0 0 0</pose><geometry><box><size>0.4 0.4 0.03</size></box></geometry>
        <material><ambient>{rgb}</ambient><diffuse>{rgb}</diffuse></material></visual>"""]
        for k_, (r_, z0, hh, c_) in enumerate(((0.14, 0.03, 0.22, rgb), (0.10, 0.25, 0.22, COLORS["white"]),
                                               (0.06, 0.47, 0.23, rgb))):
            parts.append(f"""<visual name="c{k_}"><pose>0 0 {z0 + hh/2} 0 0 0</pose><geometry><cylinder><radius>{r_}</radius><length>{hh}</length></cylinder></geometry>
        <material><ambient>{c_}</ambient><diffuse>{c_}</diffuse></material></visual>""")
        vis = "\n        ".join(parts)
        cgeom = f"<cylinder><radius>0.12</radius><length>{h}</length></cylinder>"
    cz = h / 2 if shape != "cone" else h / 2
    obst_models.append(f"""
    <model name="obstacle_{idx:02d}_{base}"><static>true</static><pose>{px:.3f} {py:.3f} {Z_ROAD} 0 0 {yaw:.4f}</pose><link name="l">
        {vis}
        <collision name="c"><pose>0 0 {cz} 0 0 0</pose><geometry>{cgeom}</geometry></collision>
    </link></model>""")

# roadside posts / tyre-like stacks outside the edge (extra lidar returns)
for j, s in enumerate(range(10, int(LAP), 40)):
    side = 1 if j % 2 == 0 else -1
    i = int(s / DS) % N
    if int(PIT_S0 / DS) - 5 <= i <= int(PIT_S1 / DS) + 5 and side < 0:
        continue                                     # keep the pit lane clear
    if side < 0 and any(abs(s - t) < 4 for t in STOPS):
        continue                                     # stop sign stands here
    px, py = off(i, side * (half + 2.0))
    col = COLORS["red"] if j % 2 == 0 else COLORS["white"]
    obst_models.append(f"""
    <model name="post_{j:02d}"><static>true</static><pose>{px:.3f} {py:.3f} 0 0 0 0</pose><link name="l">
        <visual name="v"><pose>0 0 0.5 0 0 0</pose><geometry><cylinder><radius>0.25</radius><length>1.0</length></cylinder></geometry>
        <material><ambient>{col}</ambient><diffuse>{col}</diffuse></material></visual>
        <collision name="c"><pose>0 0 0.5 0 0 0</pose><geometry><cylinder><radius>0.25</radius><length>1.0</length></cylinder></geometry></collision>
    </link></model>""")


# --- stop signs (right-hand side of the road, facing oncoming cars) + stop lines
from PIL import Image, ImageDraw, ImageFont
TEX = 512
img = Image.new("RGB", (TEX, TEX), (255, 255, 255))
dr = ImageDraw.Draw(img)
def _oct(r):
    return [(TEX / 2 + r * math.cos(math.radians(22.5 + 45 * k)),
             TEX / 2 - r * math.sin(math.radians(22.5 + 45 * k))) for k in range(8)]
dr.polygon(_oct(TEX / 2), fill=(255, 255, 255))
dr.polygon(_oct(TEX / 2 * 0.93), fill=(200, 16, 30))
font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 150)
dr.text((TEX / 2, TEX / 2), "STOP", font=font, fill=(255, 255, 255), anchor="mm")
img.save(os.path.join(out, "stop_sign.png"))

SIGN_R = 0.375 / math.cos(math.radians(22.5))   # 0.75 m across flats
def octagon_obj(path, front):
    ang = [math.radians(22.5 + 45 * k) for k in range(8)]
    with open(path, "w") as fh:
        fh.write("# stop sign octagon in the y-z plane\n")
        fh.write("v 0 0 0\n")
        for a in ang:
            fh.write(f"v 0 {-SIGN_R * math.cos(a):.4f} {SIGN_R * math.sin(a):.4f}\n")
        fh.write("vt 0.5 0.5\n")
        for a in ang:
            fh.write(f"vt {0.5 + 0.5 * math.cos(a):.4f} {0.5 + 0.5 * math.sin(a):.4f}\n")
        fh.write(f"vn {-1 if front else 1} 0 0\n")
        for k in range(8):
            a, b = 2 + k, 2 + (k + 1) % 8
            if front:
                fh.write(f"f 1/1/1 {a}/{a}/1 {b}/{b}/1\n")
            else:
                fh.write(f"f 1/1/1 {b}/{b}/1 {a}/{a}/1\n")
octagon_obj(os.path.join(out, "stop_front.obj"), True)
octagon_obj(os.path.join(out, "stop_back.obj"), False)

def tpt(i, t, d):
    """Point at arc offset t (m) after sample i and lateral offset d."""
    x, y = off(i, d)
    return (x + NORM[i % N][1] * t, y - NORM[i % N][0] * t)

stop_lines = Mesh()
SIGN_D = -(half + 1.2)                          # 1.2 m outside the right edge
for st in STOPS:
    i = int(st / DS) % N
    # stop line across the right lane, 1.5 m after the sign
    stop_lines.quad(tpt(i, 1.5, -half + 0.15), tpt(i, 1.9, -half + 0.15),
                    tpt(i, 1.9, -0.15), tpt(i, 1.5, -0.15), Z_LINE)
    px, py = off(i, SIGN_D)
    yaw = math.atan2(-NORM[i][0], NORM[i][1])
    hs = 2.0                                      # sign centre height (m)
    obst_models.append(f"""
    <model name="stop_sign_{int(st):04d}"><static>true</static><pose>{px:.3f} {py:.3f} 0 0 0 {yaw:.4f}</pose><link name="l">
        <visual name="pole"><pose>0.04 0 {hs/2} 0 0 0</pose><geometry><cylinder><radius>0.03</radius><length>{hs}</length></cylinder></geometry>
          <material><ambient>0.6 0.6 0.62 1</ambient><diffuse>0.6 0.6 0.62 1</diffuse></material></visual>
        <visual name="face"><pose>0 0 {hs} 0 0 0</pose><geometry><mesh><uri>file://{absout}/stop_front.obj</uri></mesh></geometry>
          <material><diffuse>1 1 1 1</diffuse><pbr><metal><albedo_map>file://{absout}/stop_sign.png</albedo_map><metalness>0</metalness><roughness>0.6</roughness></metal></pbr></material>{label_plugin(5)}</visual>
        <visual name="back"><pose>0.01 0 {hs} 0 0 0</pose><geometry><mesh><uri>file://{absout}/stop_back.obj</uri></mesh></geometry>
          <material><ambient>0.7 0.7 0.7 1</ambient><diffuse>0.7 0.7 0.7 1</diffuse></material></visual>
        <collision name="c"><pose>0.04 0 {hs/2} 0 0 0</pose><geometry><cylinder><radius>0.05</radius><length>{hs}</length></cylinder></geometry></collision>
    </link></model>""")
stop_lines.save(os.path.join(out, "stop_lines.obj"))

xs = [p[0] for p in CL]
ys = [p[1] for p in CL]
cx, cy = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
gx, gy = (max(xs) - min(xs)) + 200, (max(ys) - min(ys)) + 200

sdf = f"""<?xml version="1.0"?>
<sdf version="1.7">
  <world name="shell_eco_track">
    <physics name="1ms" type="ignored"><max_step_size>0.001</max_step_size><real_time_factor>1.0</real_time_factor></physics>
    <plugin filename="ignition-gazebo-physics-system" name="ignition::gazebo::systems::Physics"/>
    <plugin filename="ignition-gazebo-user-commands-system" name="ignition::gazebo::systems::UserCommands"/>
    <plugin filename="ignition-gazebo-scene-broadcaster-system" name="ignition::gazebo::systems::SceneBroadcaster"/>
    <plugin filename="ignition-gazebo-sensors-system" name="ignition::gazebo::systems::Sensors"><render_engine>ogre2</render_engine></plugin>
    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows><pose>0 0 50 0 0 0</pose>
      <diffuse>1 1 0.95 1</diffuse><specular>0.3 0.3 0.3 1</specular>
      <direction>-0.4 0.3 -1</direction>
    </light>
    <model name="grass"><static>true</static><pose>{cx:.2f} {cy:.2f} -0.05 0 0 0</pose><link name="l">
      <collision name="c"><geometry><box><size>{gx:.1f} {gy:.1f} 0.1</size></box></geometry>
        <surface><friction><ode><mu>0.8</mu><mu2>0.8</mu2></ode></friction></surface></collision>
      <visual name="v"><geometry><box><size>{gx:.1f} {gy:.1f} 0.1</size></box></geometry>
        <material><ambient>0.25 0.45 0.2 1</ambient><diffuse>0.25 0.45 0.2 1</diffuse></material></visual>
    </link></model>{model("road", "road", "0.2 0.2 0.2 1", True)}{model("pit_lane", "pit_lane", "0.28 0.28 0.3 1", True)}{model("edge_lines", "edge_lines", "1 1 1 1", False, 1)}{model("start_line", "start_line", "1 1 1 1", False, 4)}{model("stop_lines", "stop_lines", "1 1 1 1", False, 3)}{"".join(obst_models)}
  </world>
</sdf>
"""
with open(os.path.join(out, "shell_eco_track.sdf"), "w") as fh:
    fh.write(sdf)

